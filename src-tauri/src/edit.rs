//! The Edit tab's bake: a render plan from the frontend, turned into an ffmpeg
//! filter graph and encoded to an ordinary MP4.
//!
//! Every placement decision is made in TypeScript (`src/lib/editPlan.ts`), so
//! the preview and the bake share one set of maths. This side only translates:
//! one input per layer, seeked at the demuxer so a clip late in a long source
//! does not decode everything before it, each layer faded in alpha and laid
//! over black. The graph holds no paths — inputs go on the command line — and
//! is written to a file, since Windows caps a command line at about 32k chars.

use crate::error::{AppError, AppResult};
use crate::ffmpeg_job::FfmpegJob;
use crate::media::{ffmpeg_bin, quiet_command};
use serde::{Deserialize, Serialize};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use tauri::{AppHandle, Emitter, Manager};

#[derive(Default)]
pub struct BakeState {
    job: FfmpegJob,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PlanRect {
    /// Seconds into the layer. Only the first rect is drawn until keyframed
    /// transforms are baked.
    #[allow(dead_code)]
    pub time: f64,
    pub x: f64,
    pub y: f64,
    pub w: f64,
    pub h: f64,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PlanAudio {
    pub gain_db: f64,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PlanLayer {
    /// "video" or "image".
    pub kind: String,
    pub path: String,
    /// A PNG staged in the work dir by `stage_edit_image`, named not pathed.
    pub staged: bool,
    pub start: f64,
    pub duration: f64,
    pub offset: f64,
    pub fade_in: f64,
    pub fade_out: f64,
    pub opacity: f64,
    pub rects: Vec<PlanRect>,
    pub audio: Option<PlanAudio>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RenderPlan {
    pub width: u32,
    pub height: u32,
    pub fps: f64,
    pub total: f64,
    pub layers: Vec<PlanLayer>,
}

#[derive(Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BakeProgress {
    pub fraction: f64,
    pub time_seconds: f64,
    pub speed: String,
}

/// A number for ffmpeg: up to microseconds, without trailing zeros.
fn num(value: f64) -> String {
    let fixed = format!("{value:.6}");
    let trimmed = fixed.trim_end_matches('0').trim_end_matches('.');
    if trimmed.is_empty() || trimmed == "-0" {
        "0".to_string()
    } else {
        trimmed.to_string()
    }
}

/// The NTSC rates as exact rationals, so 29.97 does not drift a frame an hour.
fn rate(fps: f64) -> String {
    for (num_, den) in [(24000, 1001), (30000, 1001), (60000, 1001)] {
        if (fps - num_ as f64 / den as f64).abs() < 0.005 {
            return format!("{num_}/{den}");
        }
    }
    num(fps)
}

/// A staged file's name: generated by the frontend, plain ASCII, nothing else.
fn valid_staged_name(name: &str) -> bool {
    let Some(stem) = name.strip_suffix(".png") else {
        return false;
    };
    !stem.is_empty()
        && stem.len() <= 64
        && stem
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-' || b == b'_')
}

/// The input arguments and filter graph for a plan. Pure, for the tests.
pub fn build_graph(plan: &RenderPlan) -> AppResult<(Vec<String>, String)> {
    if plan.width == 0 || plan.height == 0 || !plan.width.is_multiple_of(2) || !plan.height.is_multiple_of(2) {
        return Err(AppError::msg("The canvas size must be even and not zero."));
    }
    // Written to catch NaN too: it is neither above nor below zero.
    let positive = |v: f64| v.is_finite() && v > 0.0;
    if !positive(plan.fps) || !positive(plan.total) {
        return Err(AppError::msg("There is nothing on the timeline to bake."));
    }
    let fps = rate(plan.fps);
    let mut inputs: Vec<String> = Vec::new();
    let mut graph = String::new();
    let mut audio_labels: Vec<String> = Vec::new();

    // Composited in planar RGB, and only made 4:2:0 at the very end: an
    // overlay onto a yuv420p base snaps to even pixels, which would put
    // anything at an odd position a pixel away from where the preview draws it.
    let _ = writeln!(
        graph,
        "color=c=black:s={}x{}:r={fps}:d={},format=gbrp[b0];",
        plan.width,
        plan.height,
        num(plan.total)
    );

    let mut base = 0usize;
    for (index, layer) in plan.layers.iter().enumerate() {
        if !positive(layer.duration) {
            return Err(AppError::msg("A layer in the plan has no length."));
        }
        let Some(rect) = layer.rects.first() else {
            return Err(AppError::msg("A layer in the plan has no placement."));
        };
        if layer.staged && !valid_staged_name(&layer.path) {
            return Err(AppError::msg(format!("Not a staged image name: {}", layer.path)));
        }

        match layer.kind.as_str() {
            "video" => inputs.extend([
                "-ss".into(),
                num(layer.offset.max(0.0)),
                "-t".into(),
                num(layer.duration),
                "-i".into(),
                layer.path.clone(),
            ]),
            "image" => inputs.extend([
                "-loop".into(),
                "1".into(),
                "-framerate".into(),
                fps.clone(),
                "-t".into(),
                num(layer.duration),
                "-i".into(),
                layer.path.clone(),
            ]),
            other => return Err(AppError::msg(format!("Unknown layer kind: {other}"))),
        }

        // Picture: normalised to the canvas rate, sized, faded in alpha, and
        // moved to its place on the timeline.
        let end = layer.start + layer.duration;
        let mut chain = format!(
            "[{index}:v]setpts=PTS-STARTPTS,fps={fps},scale={}:{},format=rgba",
            rect.w.max(1.0).round(),
            rect.h.max(1.0).round()
        );
        if layer.opacity < 1.0 {
            let _ = write!(chain, ",colorchannelmixer=aa={}", num(layer.opacity.max(0.0)));
        }
        if layer.fade_in > 0.0 {
            let _ = write!(chain, ",fade=t=in:st=0:d={}:alpha=1", num(layer.fade_in));
        }
        if layer.fade_out > 0.0 {
            let _ = write!(
                chain,
                ",fade=t=out:st={}:d={}:alpha=1",
                num((layer.duration - layer.fade_out).max(0.0)),
                num(layer.fade_out)
            );
        }
        let _ = writeln!(chain, ",setpts=PTS+{}/TB[v{index}];", num(layer.start));
        graph.push_str(&chain);
        let _ = writeln!(
            graph,
            "[b{base}][v{index}]overlay=x={}:y={}:eof_action=pass:format=gbrp:enable='between(t,{},{})'[b{}];",
            rect.x.round(),
            rect.y.round(),
            num(layer.start),
            num(end),
            base + 1
        );
        base += 1;

        // Sound, for main-track video that has it.
        if let Some(audio) = &layer.audio {
            let mut chain = format!(
                "[{index}:a]asetpts=PTS-STARTPTS,aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo"
            );
            if layer.fade_in > 0.0 {
                let _ = write!(chain, ",afade=t=in:st=0:d={}", num(layer.fade_in));
            }
            if layer.fade_out > 0.0 {
                let _ = write!(
                    chain,
                    ",afade=t=out:st={}:d={}",
                    num((layer.duration - layer.fade_out).max(0.0)),
                    num(layer.fade_out)
                );
            }
            if audio.gain_db != 0.0 {
                let _ = write!(chain, ",volume={}dB", num(audio.gain_db));
            }
            let delay_ms = (layer.start * 1000.0).round().max(0.0) as u64;
            let _ = writeln!(chain, ",adelay={delay_ms}:all=1[a{index}];");
            graph.push_str(&chain);
            audio_labels.push(format!("[a{index}]"));
        }
    }

    let _ = writeln!(graph, "[b{base}]format=yuv420p[vout];");
    // A silent bed the length of the edit, so gaps are silence and the
    // soundtrack runs exactly as long as the picture.
    let _ = write!(
        graph,
        "anullsrc=r=48000:cl=stereo,atrim=0:{}[bed];",
        num(plan.total)
    );
    if audio_labels.is_empty() {
        graph.push_str("\n[bed]anull[aout]\n");
    } else {
        let _ = writeln!(
            graph,
            "\n[bed]{}amix=inputs={}:normalize=0:duration=first[aout]",
            audio_labels.concat(),
            audio_labels.len() + 1
        );
    }
    Ok((inputs, graph))
}

fn work_dir(app: &AppHandle) -> AppResult<PathBuf> {
    let dir = app
        .path()
        .app_cache_dir()
        .map_err(|e| AppError::msg(format!("No cache directory: {e}")))?
        .join("edit");
    std::fs::create_dir_all(&dir)?;
    Ok(dir)
}

/// Same file, as far as can be told without it existing.
fn same_file(a: &Path, b: &Path) -> bool {
    if let (Ok(ca), Ok(cb)) = (a.canonicalize(), b.canonicalize()) {
        return ca == cb;
    }
    let norm = |p: &Path| p.to_string_lossy().replace('\\', "/").to_lowercase();
    norm(a) == norm(b)
}

/// Writes one PNG — a text item drawn by the frontend — into the bake's work
/// dir. The body is the raw bytes; the `x-name` header names the file.
#[tauri::command]
pub fn stage_edit_image(app: AppHandle, request: tauri::ipc::Request<'_>) -> AppResult<String> {
    let tauri::ipc::InvokeBody::Raw(bytes) = request.body() else {
        return Err(AppError::msg("Expected the image as raw bytes."));
    };
    let name = request
        .headers()
        .get("x-name")
        .and_then(|v| v.to_str().ok())
        .unwrap_or_default()
        .to_string();
    if !valid_staged_name(&name) {
        return Err(AppError::msg(format!("Not a usable image name: {name}")));
    }
    if !bytes.starts_with(b"\x89PNG\r\n\x1a\n") {
        return Err(AppError::msg("That is not a PNG."));
    }
    std::fs::write(work_dir(&app)?.join(&name), bytes)
        .map_err(|e| AppError::msg(format!("Could not stage {name}: {e}")))?;
    Ok(name)
}

#[tauri::command]
pub fn cancel_bake(state: tauri::State<'_, BakeState>) -> AppResult<()> {
    state.job.cancel("bake")
}

#[tauri::command]
pub async fn bake_edit(
    app: AppHandle,
    state: tauri::State<'_, BakeState>,
    plan: RenderPlan,
    output_path: String,
    crf: Option<u32>,
) -> AppResult<()> {
    let output = PathBuf::from(&output_path);
    for layer in plan.layers.iter().filter(|l| !l.staged) {
        if same_file(&output, Path::new(&layer.path)) {
            return Err(AppError::msg(
                "The bake would overwrite one of its sources. Choose another name.",
            ));
        }
    }

    let (inputs, graph) = build_graph(&plan)?;
    let dir = work_dir(&app)?;
    std::fs::write(dir.join("graph.txt"), &graph)
        .map_err(|e| AppError::msg(format!("Could not write the filter graph: {e}")))?;
    let crf = crf.unwrap_or(18).clamp(0, 51);

    let mut args: Vec<String> = ["-hide_banner", "-nostdin", "-y"].map(String::from).to_vec();
    args.extend(inputs);
    args.extend(
        [
            "-filter_complex_script", "graph.txt",
            "-map", "[vout]", "-map", "[aout]",
            "-c:v", "libx264", "-crf", &crf.to_string(), "-preset", "medium",
            "-pix_fmt", "yuv420p", "-r", &rate(plan.fps),
            "-c:a", "aac", "-b:a", "192k",
            "-movflags", "+faststart",
            "-nostats", "-progress", "pipe:1",
        ]
        .map(String::from),
    );
    args.push(output_path.clone());

    // Windows refuses a command line past 32,767 characters; say so plainly
    // rather than fail to start.
    let length: usize = args.iter().map(|a| a.len() + 3).sum();
    if cfg!(windows) && length > 30_000 {
        return Err(AppError::msg(
            "This edit has too many clips to bake in one go. Bake part of it first.",
        ));
    }

    state.job.reset();
    let mut command = quiet_command(&ffmpeg_bin());
    // Relative names (the graph, staged images) resolve in the work dir.
    command.current_dir(&dir).args(&args);
    let progress_app = app.clone();
    let result = state
        .job
        .run(command, plan.total, "bake", move |p| {
            let _ = progress_app.emit(
                "bake-progress",
                BakeProgress {
                    fraction: p.fraction,
                    time_seconds: p.time_seconds,
                    speed: p.speed,
                },
            );
        })
        .await;

    for layer in plan.layers.iter().filter(|l| l.staged) {
        let _ = std::fs::remove_file(dir.join(&layer.path));
    }
    if result.is_err() {
        // A cancelled or failed bake leaves no half-written file behind.
        let _ = std::fs::remove_file(&output);
    }
    result
}

/// Sends a bake that nothing uses any more to the Recycle Bin. Only files
/// that look like bakes, so a wrong path can never take a source with it.
#[tauri::command]
pub fn trash_bake(path: String) -> AppResult<()> {
    let p = Path::new(&path);
    let name = p
        .file_name()
        .map(|n| n.to_string_lossy().to_lowercase())
        .unwrap_or_default();
    let looks_baked = name.ends_with(".mp4") && name.contains(".cut");
    if !looks_baked {
        return Err(AppError::msg(format!("Not a bake: {path}")));
    }
    if !p.is_file() {
        return Ok(());
    }
    trash::delete(p).map_err(|e| AppError::msg(format!("Could not move {path} to the Recycle Bin: {e}")))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rect(w: f64, h: f64) -> Vec<PlanRect> {
        vec![PlanRect { time: 0.0, x: 0.0, y: 0.0, w, h }]
    }

    fn video(start: f64, duration: f64, offset: f64, audio: bool) -> PlanLayer {
        PlanLayer {
            kind: "video".into(),
            path: "/v/a.mp4".into(),
            staged: false,
            start,
            duration,
            offset,
            fade_in: 0.0,
            fade_out: 0.0,
            opacity: 1.0,
            rects: rect(640.0, 360.0),
            audio: audio.then_some(PlanAudio { gain_db: 0.0 }),
        }
    }

    fn plan(layers: Vec<PlanLayer>, total: f64) -> RenderPlan {
        RenderPlan { width: 640, height: 360, fps: 25.0, total, layers }
    }

    #[test]
    fn seeks_each_clip_at_the_demuxer_and_places_it_in_time() {
        let (inputs, graph) =
            build_graph(&plan(vec![video(0.0, 4.0, 0.0, true), video(5.0, 6.0, 12.5, true)], 11.0)).unwrap();
        assert_eq!(
            inputs,
            ["-ss", "0", "-t", "4", "-i", "/v/a.mp4", "-ss", "12.5", "-t", "6", "-i", "/v/a.mp4"]
        );
        assert!(graph.starts_with("color=c=black:s=640x360:r=25:d=11,format=gbrp[b0];"));
        assert!(graph.contains("[1:v]setpts=PTS-STARTPTS,fps=25,scale=640:360,format=rgba,setpts=PTS+5/TB[v1];"));
        // The gap from 4 to 5 s is the black base: nothing is enabled over it.
        assert!(graph.contains("[b0][v0]overlay=x=0:y=0:eof_action=pass:format=gbrp:enable='between(t,0,4)'[b1];"));
        assert!(graph.contains("[b1][v1]overlay=x=0:y=0:eof_action=pass:format=gbrp:enable='between(t,5,11)'[b2];"));
        assert!(graph.contains("[b2]format=yuv420p[vout];"));
        assert!(graph.contains("adelay=5000:all=1[a1];"));
        assert!(graph.contains("[bed][a0][a1]amix=inputs=3:normalize=0:duration=first[aout]"));
    }

    #[test]
    fn fades_alpha_and_sound_together() {
        let mut layer = video(2.0, 4.0, 0.0, true);
        layer.fade_in = 0.5;
        layer.fade_out = 1.0;
        layer.opacity = 0.8;
        let (_, graph) = build_graph(&plan(vec![layer], 6.0)).unwrap();
        assert!(graph.contains(
            "format=rgba,colorchannelmixer=aa=0.8,fade=t=in:st=0:d=0.5:alpha=1,fade=t=out:st=3:d=1:alpha=1,setpts=PTS+2/TB"
        ));
        assert!(graph.contains("afade=t=in:st=0:d=0.5,afade=t=out:st=3:d=1,adelay=2000:all=1"));
    }

    #[test]
    fn lays_a_translucent_overlay_where_its_rect_says() {
        let main = video(0.0, 5.0, 0.0, true);
        let mut logo = video(1.0, 3.0, 0.0, false);
        logo.kind = "image".into();
        logo.path = "/v/logo.png".into();
        logo.opacity = 0.5;
        logo.rects = vec![PlanRect { time: 0.0, x: 410.4, y: -12.6, w: 191.0, h: 115.0 }];
        let (inputs, graph) = build_graph(&plan(vec![main, logo], 5.0)).unwrap();
        assert_eq!(&inputs[6..], ["-loop", "1", "-framerate", "25", "-t", "3", "-i", "/v/logo.png"]);
        assert!(graph.contains("[1:v]setpts=PTS-STARTPTS,fps=25,scale=191:115,format=rgba,colorchannelmixer=aa=0.5,setpts=PTS+1/TB[v1];"));
        // Drawn over the main clip, partly off the top edge.
        assert!(graph.contains("[b1][v1]overlay=x=410:y=-13:eof_action=pass:format=gbrp:enable='between(t,1,4)'[b2];"));
        assert!(!graph.contains("[1:a]"));
    }

    #[test]
    fn a_muted_edit_is_the_silent_bed() {
        let (_, graph) = build_graph(&plan(vec![video(0.0, 3.0, 0.0, false)], 3.0)).unwrap();
        assert!(!graph.contains("[0:a]"));
        assert!(graph.contains("anullsrc=r=48000:cl=stereo,atrim=0:3[bed];"));
        assert!(graph.ends_with("[bed]anull[aout]\n"));
    }

    #[test]
    fn loops_images_and_staged_text_at_the_canvas_rate() {
        let mut image = video(1.0, 3.0, 0.0, false);
        image.kind = "image".into();
        image.path = "t-abc123.png".into();
        image.staged = true;
        let mut ntsc = plan(vec![image], 4.0);
        ntsc.fps = 29.97;
        let (inputs, graph) = build_graph(&ntsc).unwrap();
        assert_eq!(inputs, ["-loop", "1", "-framerate", "30000/1001", "-t", "3", "-i", "t-abc123.png"]);
        assert!(graph.contains("fps=30000/1001"));
    }

    #[test]
    fn refuses_unsafe_staged_names_and_odd_canvases() {
        let mut image = video(0.0, 1.0, 0.0, false);
        image.kind = "image".into();
        image.path = "../evil.png".into();
        image.staged = true;
        assert!(build_graph(&plan(vec![image], 1.0)).is_err());
        let mut odd = plan(vec![], 1.0);
        odd.width = 641;
        assert!(build_graph(&odd).is_err());
        assert!(build_graph(&plan(vec![], 0.0)).is_err());
    }

    #[test]
    fn reads_the_plan_the_frontend_sends() {
        // As `buildRenderPlan` writes it: camelCase, `audio` absent when silent.
        let json = r#"{"width":640,"height":360,"fps":25,"total":16,"layers":[
            {"kind":"video","path":"/v/a.webm","staged":false,"start":0,"duration":3,"offset":0,
             "fadeIn":0,"fadeOut":0.5,"opacity":1,"rects":[{"time":0,"x":0,"y":0,"w":640,"h":360}],
             "audio":{"gainDb":-3}},
            {"kind":"video","path":"/v/b.webm","staged":false,"start":10,"duration":6,"offset":2,
             "fadeIn":0.5,"fadeOut":0,"opacity":1,"rects":[{"time":0,"x":0,"y":0,"w":640,"h":360}]}
        ]}"#;
        let plan: RenderPlan = serde_json::from_str(json).unwrap();
        assert_eq!(plan.layers[0].fade_out, 0.5);
        assert_eq!(plan.layers[0].audio.as_ref().unwrap().gain_db, -3.0);
        assert!(plan.layers[1].audio.is_none());
        let (_, graph) = build_graph(&plan).unwrap();
        assert!(graph.contains("volume=-3dB"));
    }

    #[test]
    fn formats_numbers_for_ffmpeg() {
        assert_eq!(num(4.0), "4");
        assert_eq!(num(0.1 + 0.2), "0.3");
        assert_eq!(num(-0.0000001), "0");
        assert_eq!(rate(25.0), "25");
        assert_eq!(rate(23.976), "24000/1001");
    }
}
